#!/usr/bin/env node
// Generates the `ant apply` files (Markdown with YAML front matter, body = system prompt) from the JSON source
// in docs/meta/agents-v3. One source, no hand sync. The lead's predefined_agents become relative file paths
// (`./nemo-po.md`), which `ant apply` resolves to agent IDs in dependency order (CLI ≥ 1.40.0).
// Usage: node scripts/agents/to-ant.mjs [dir]            write nemo-*.md
//        node scripts/agents/to-ant.mjs --check [dir]    exit 1 when a .md is stale (CI/PR proof)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const check = args.includes("--check");
const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(
  args.find((a) => !a.startsWith("--")) ??
    path.join(here, "../../docs/meta/agents-v3"),
);

const files = fs
  .readdirSync(dir)
  .filter((f) => /^nemo-.*\.json$/.test(f))
  .sort();
const siblings = new Set(files.map((f) => f.replace(/\.json$/, "")));

function yamlScalar(v) {
  if (typeof v === "boolean" || typeof v === "number") return String(v);
  if (v === null) return "null";
  const s = String(v);
  if (
    /^[A-Za-z0-9_./:-]+$/.test(s) &&
    !/^(true|false|null|yes|no|on|off)$/i.test(s) &&
    !/^\d/.test(s)
  )
    return s;
  return JSON.stringify(s);
}
function yaml(v, indent = 0) {
  const pad = " ".repeat(indent);
  if (Array.isArray(v)) {
    if (v.length === 0) return pad + "[]\n";
    return v
      .map((item) => {
        if (item !== null && typeof item === "object") {
          const inner = yaml(item, indent + 2).trimStart();
          return pad + "- " + inner;
        }
        return pad + "- " + yamlScalar(item) + "\n";
      })
      .join("");
  }
  if (v !== null && typeof v === "object") {
    const keys = Object.keys(v);
    if (keys.length === 0) return pad + "{}\n";
    return keys
      .map((k) => {
        const val = v[k];
        if (val !== null && typeof val === "object") {
          const inner = yaml(val, indent + 2);
          if (Array.isArray(val) && val.length === 0) return `${pad}${k}: []\n`;
          if (!Array.isArray(val) && Object.keys(val).length === 0)
            return `${pad}${k}: {}\n`;
          return `${pad}${k}:\n${inner}`;
        }
        return `${pad}${k}: ${yamlScalar(val)}\n`;
      })
      .join("");
  }
  return pad + yamlScalar(v) + "\n";
}

function toAnt(a) {
  const fm = { name: a.name };
  if (a.description) fm.description = a.description;
  fm.model = a.model;
  if (a.tools) fm.tools = a.tools;
  if (a.mcp_servers) fm.mcp_servers = a.mcp_servers;
  if (a.skills && a.skills.length) fm.skills = a.skills;
  if (a.multiagent) {
    const ma = structuredClone(a.multiagent);
    for (const list of [
      ma.subagents?.predefined_agents,
      ma.workflows?.predefined_agents,
    ]) {
      if (!list) continue;
      list.forEach((p, i) => {
        const ref = typeof p === "string" ? p : p.id;
        if (siblings.has(ref))
          list[i] = `./${ref}.md`; // path reference, resolved by ant apply
        else if (!/^agent_/.test(ref))
          throw new Error(`${a.name}: predefined agent "${ref}" unknown`);
      });
    }
    fm.multiagent = ma;
  }
  if (a.metadata && Object.keys(a.metadata).length) fm.metadata = a.metadata;
  return `---\n# generated by scripts/agents/to-ant.mjs from ${a.name}.json – edit the JSON, not this file\n${yaml(fm)}---\n\n${a.system.trimEnd()}\n`;
}

let stale = 0;
for (const f of files) {
  const a = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  const out = path.join(dir, f.replace(/\.json$/, ".md"));
  const md = toAnt(a);
  if (check) {
    const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
    if (cur !== md) {
      stale++;
      console.log(`✗ stale: ${path.basename(out)}`);
    }
  } else {
    fs.writeFileSync(out, md);
    console.log(`wrote ${path.basename(out)} (${md.length} chars)`);
  }
}
if (check) {
  console.log(
    stale
      ? `${stale} file(s) stale – run node scripts/agents/to-ant.mjs`
      : `✓ ${files.length} .md files match their JSON`,
  );
  process.exit(stale ? 1 : 0);
}
