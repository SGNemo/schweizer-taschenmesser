/** Instant of phase k (integer + 0 new, .25 first quarter, .5 full, .75 last quarter; k=0 ~ 2000-01-06). */
export function phaseInstant(k) {
  const T = k / 1236.85, T2 = T * T, T3 = T2 * T, T4 = T3 * T;
  let jde = 2451550.09766 + 29.530588861 * k + 0.00015437 * T2 - 0.00000015 * T3 + 0.00000000073 * T4;
  const E = 1 - 0.002516 * T - 0.0000074 * T2;
  const M = 2.5534 + 29.1053567 * k - 0.0000014 * T2 - 0.00000011 * T3;
  const Mp = 201.5643 + 385.81693528 * k + 0.0107582 * T2 + 0.00001238 * T3 - 0.000000058 * T4;
  const F = 160.7108 + 390.67050284 * k - 0.0016118 * T2 - 0.00000227 * T3 + 0.000000011 * T4;
  const Om = 124.7746 - 1.56375588 * k + 0.0020672 * T2 + 0.00000215 * T3;
  const frac = ((k % 1) + 1) % 1;
  const tab = frac < 0.1 ? NEW : Math.abs(frac - 0.5) < 0.1 ? FULL : QUARTER;
  for (const [c, e, a, b, f, o] of tab) jde += c * E ** e * sind(a * M + b * Mp + f * F + o * Om);
  if (tab === QUARTER) {
    const W = 0.00306 - 0.00038 * E * cosd(M) + 0.00026 * cosd(Mp) - 0.00002 * cosd(Mp - M)
      + 0.00002 * cosd(Mp + M) + 0.00002 * cosd(2 * F);
    jde += Math.abs(frac - 0.25) < 0.1 ? W : -W;
  }
  PLAN.forEach(([a, b, c], i) => { jde += c * 1e-6 * sind(a + b * k - (i === 0 ? 0.009173 * T2 : 0)); });
  return ttToMs(jde);
}

/** All principal phases with instants in [fromMs, toMs): [{ms, phase: 0|1|2|3}] (0 new..3 last quarter). */
export function phasesBetween(fromMs, toMs) {
  const yr = 2000 + (fromMs / 86400000 + 2440587.5 - 2451545) / 365.25;
  let k = Math.floor((yr - 2000) * 12.3685) - 1;
  const out = [];
  for (;; k += 0.25) {
    const ms = phaseInstant(k);
    if (ms >= toMs) break;
    if (ms >= fromMs) out.push({ ms, phase: Math.round((((k % 1) + 1) % 1) * 4) % 4 });
  }
  return out;
}

