export function Logo({
  size = 32,
  title,
  mono = false,
  tile = false,
}: {
  size?: number;
  title?: string;
  mono?: boolean;
  tile?: boolean;
}) {
  const cut = useId();
  const inside = `${cut}-b`;
  // `--logo-ink` is only set by the supporter option "Logo in Themenfarbe" (ui/supporterThemes.css).
  const ink = mono ? 'currentColor' : `var(--logo-ink, ${LOGO_COLOR})`;
  const fish = tile ? 'var(--accent-contrast)' : ink;
  const mark = (
    <g
      fill={fish}
      stroke={fish}
      strokeWidth={LOGO_SOFTEN}
      strokeLinejoin="round"
      mask={`url(#${cut})`}
    >
      <path d={LOGO_PATHS.body} />
      <path d={LOGO_PATHS.tail} />
    </g>
  );
  return (
    <svg
      viewBox={tile ? '0 0 512 512' : LOGO_VIEWBOX}
      height={tile ? '100%' : size}
      width={tile ? '100%' : Math.round(size * LOGO_ASPECT)}
      role={title ? 'img' : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
    >
      <defs>
        <clipPath id={inside}>
          <path d={LOGO_PATHS.body} />
        </clipPath>
        <mask id={cut} maskUnits="userSpaceOnUse" x="-512" y="-512" width="1536" height="1536">
          <rect x="-512" y="-512" width="1536" height="1536" fill="#fff" />
          <g fill="none" stroke="#000" clipPath={`url(#${inside})`}>
            <path d={LOGO_PATHS.cut1} strokeWidth={LOGO_CUT_WIDTH} />
            <path d={LOGO_PATHS.cut2} strokeWidth={LOGO_CUT_WIDTH} />
          </g>
          {/* The bands are cut inside the body only; this stroke on its outline puts the rim back. */}
          <path
            d={LOGO_PATHS.body}
            fill="none"
            stroke="#fff"
            strokeWidth={LOGO_RIM}
            strokeLinejoin="round"
          />
          <circle cx={LOGO_EYE.cx} cy={LOGO_EYE.cy} r={LOGO_EYE.r} fill="#000" />
        </mask>
      </defs>
      {tile ? (
        <>
          <rect
            width="512"
            height="512"
            rx={LOGO_TILE.radius}
            fill={`var(--logo-ink, ${LOGO_COLOR})`}
          />
          <g transform={LOGO_TILE.transform}>{mark}</g>
        </>
      ) : (
        mark
      )}
    </svg>
  );
}
