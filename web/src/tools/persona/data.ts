/**
 * Word lists of the persona generator: invented street names, common first and last names, real cities with
 * the postcode ranges that belong to them. Written for this app (no third-party list, nothing to license);
 * names are common given names and surnames, not people. Streets are made up on purpose ("Beispielweg"):
 * a real street name combined with a real postcode could name a real person's address.
 * Phone numbers: Germany and the USA use the ranges that the national regulators reserved for fiction
 * (Bundesnetzagentur "Drama Numbers"; NANP 555-0100 to 555-0199); for the others there is no range we could
 * verify, so numbers are clearly invalid (they start with a digit no real number starts with).
 */

export const COUNTRIES = ['de', 'us', 'fr', 'es', 'br'] as const;
export type CountryId = (typeof COUNTRIES)[number];

export interface City {
  name: string;
  /** Postcode prefix range (inclusive), or an explicit list. */
  range?: readonly [number, number];
  list?: readonly string[];
  /** Area code (USA) or a key into the German drama-number table. */
  area?: string;
}

export interface CountryData {
  female: readonly string[];
  male: readonly string[];
  last: readonly string[];
  cities: readonly City[];
  streets: readonly string[];
  /** "Musterstraße 12", "12 Example St", … */
  street(name: string, no: number): string;
  interests: readonly string[];
  bio(three: readonly string[]): string;
}

